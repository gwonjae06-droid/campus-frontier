import assert from 'node:assert/strict';
import {initialState,emptyPlan,resolveTurn} from './simulation.js';
import {TECHS} from './growth.js';
let s=initialState('standard');
s.research.ally.done=['development','training'];s.research.ally.active='defense';s.research.ally.progress.defense=3;
s=resolveTurn(s,emptyPlan(),{}).state;
assert.ok(s.research.ally.done.includes('defense'));
assert.equal(s.research.ally.scholarship,1);
const discounted=resolveTurn(s,{...emptyPlan(),research:'roads',scholarshipTech:'roads'},{}).state;
assert.equal(discounted.research.ally.scholarship,0);
assert.equal(discounted.research.ally.discounted.roads,3);
assert.equal(discounted.research.ally.progress.roads,3);
assert.equal(TECHS.roads.cost-discounted.research.ally.discounted.roads,7);
assert.throws(()=>resolveTurn(discounted,{...emptyPlan(),research:'roads',scholarshipTech:'roads'},{}));
const changed=resolveTurn(discounted,{...emptyPlan(),research:'methodology'},{}).state;
assert.equal(changed.research.ally.progress.roads,3);
assert.equal(changed.research.ally.discounted.roads,3);
const resumed=resolveTurn(changed,{...emptyPlan(),research:'roads'},{}).state;
assert.equal(resumed.research.ally.progress.roads,6);
const finished=resolveTurn(resumed,{...emptyPlan(),research:'roads'},{}).state;
assert.ok(finished.research.ally.done.includes('roads'));
console.log('PASS: SKKU three-tech knowledge award, one-time RP discount, reserved token spend and switching persistence');
