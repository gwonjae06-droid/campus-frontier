import assert from 'node:assert/strict';
import {initialState,emptyPlan,resolveTurn,terrain,POINT_KEYS,CENTRAL_POINT,TURN_LIMIT,victoryPoints,enemyOrders} from './simulation.js';
import {canProject} from './growth.js';
import {MIN_PITCH,MAX_PITCH,clampPitch} from './camera.js';
const s=initialState();
assert.equal(POINT_KEYS.length,7);
assert.equal(Object.keys(s.points).length,7);
assert.equal(terrain(10,10),'resource');
assert.equal(victoryPoints(s,'ally'),5);
assert.equal(victoryPoints(s,'enemy'),5);
s.points[CENTRAL_POINT]='ally';s.pointReady[CENTRAL_POINT]=1;
assert.equal(victoryPoints(s,'ally'),10);
s.research.ally.done=['training'];
assert.equal(victoryPoints(s,'ally'),12);
assert.ok(canProject(s,emptyPlan(),{site:CENTRAL_POINT,type:'science'},100));
assert.equal(enemyOrders(s).e1?.type,'move');
const round=initialState();round.turn=TURN_LIMIT;round.research.ally.done=['training'];
const finished=resolveTurn(round,emptyPlan(),{});
assert.equal(finished.state.result,'victory');
assert.equal(finished.state.victoryMode,'score');
assert.ok(finished.events.some(e=>e.type==='score'));
const even=initialState();even.turn=TURN_LIMIT;even.units=[];even.research.enemy.done=[];const draw=resolveTurn(even,emptyPlan(),{});
assert.equal(draw.state.result,'draw');
assert.equal(draw.state.victoryMode,'score');
assert.equal(MIN_PITCH,50);assert.equal(MAX_PITCH,62);
assert.equal(clampPitch(-100),50);assert.equal(clampPitch(100),62);
console.log('PASS: 7 outposts, central objective, score victory/draw, tech points, new camera bounds');
