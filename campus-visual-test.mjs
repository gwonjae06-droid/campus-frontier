import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import * as THREE from './vendor/three.module.js';
import {makeRivalCampus} from './rival-campuses.js';
import {makeCampus} from './campus.js';
import {CAMPUS,isCampus,isEnemyCampus,isRivalCampus,passable,initialState,GATES,ENEMY_GATES,RIVAL_GATES} from './simulation.js';
import {visibleTiles} from './vision.js';
assert.equal(CAMPUS.size,4);
for(let x=2;x<=5;x++)for(let z=2;z<=5;z++)assert.ok(isCampus(x,z));
for(let x=15;x<=18;x++)for(let z=15;z<=18;z++)assert.ok(isEnemyCampus(x,z));
for(let x=15;x<=18;x++)for(let z=2;z<=5;z++)assert.ok(isRivalCampus(x,z));
assert.equal([[isCampus,2,5],[isEnemyCampus,15,18],[isRivalCampus,18,2]].every(([f,x,z])=>f(x,z)),true);
const s=initialState('standard');
assert.equal(s.version,13);
assert.ok(s.units.every(u=>passable(u.x,u.z)));
for(const g of [...GATES,...ENEMY_GATES,...RIVAL_GATES])assert.ok(passable(g.x,g.z),`invalid gate at ${g.x},${g.z}`);
const official=makeCampus(JSON.parse(readFileSync('data/skku-campus.json','utf8')));
assert.equal(official.group.userData.buildingCount,56);
const a=new THREE.Box3().setFromObject(official.group);assert.ok(a.max.x-a.min.x<4.48);assert.ok(a.max.z-a.min.z<4.48);
assert.ok(a.min.y>=-.005,'ground must be flush, not raised on a slab');
for(const which of ['yonsei','korea']){
 const model=makeRivalCampus(which);
 assert.ok(model.buildingCount>=7);
 const bb=new THREE.Box3().setFromObject(model.group);
 assert.ok(bb.max.x-bb.min.x<4.48&&bb.max.z-bb.min.z<4.48);
 assert.ok(bb.min.y>=-.005,`${which} must touch ground without raised plinth`);
 assert.ok(model.picks.every(o=>typeof o.userData.building.n==='string'));
}
const board=readFileSync('board.js','utf8');
assert.ok(board.includes("makeCampus(rivalData.korea,'korea')"));
assert.ok(board.includes("makeCampus(rivalData.yonsei,'yonsei')"));
assert.ok(board.includes('fog.frustumCulled=false'));
assert.ok(board.includes("g.visible=state.gameMode!=='standard'||explored.has(k)"));
assert.ok(board.includes('transparent:false'));
assert.ok(board.includes('makeRivalCampus'));
assert.ok(!board.includes('BoxGeometry(1.107,9.4,1.107)'));
const visible=visibleTiles(s,'ally');assert.ok(visible.size<300);
assert.ok(!visible.has('10,10'),'central map needs fog before scouting');
const js=readFileSync('game.js','utf8');
assert.ok(js.includes('function treePosition(id)'), 'skill tree settings must be hoisted before initial rendering');
assert.ok(js.includes('renderTreeConnections'));
const html=readFileSync('index.html','utf8');
for(const name of ['성균관대학교','인문사회과학캠퍼스','연세대학교 신촌캠퍼스','고려대학교 안암캠퍼스'])assert.ok(html.includes(name),`missing ${name}`);
console.log('PASS: all 4x4 campuses, grounded campus miniatures, fog visibility, and skill tree initialization');
