import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import * as THREE from './vendor/three.module.js';
import {makeCampus} from './campus.js';
import {initialState,emptyPlan,resolveTurn,enemyOrders,canMove,terrain} from './simulation.js';
import {canResearch} from './growth.js';
for(const [name,count] of [['yonsei-sinchon',232],['korea-anam',172]]){
 const src=JSON.parse(readFileSync(`data/${name}.json`,'utf8'));
 assert.equal(src.buildings.length,count,`${name} must contain original OSM-derived footprint count`);
 assert.equal(src.meta.license,'ODbL-1.0');
 assert.equal(src.meta.simplifiedTerrain,true);
 assert.ok(src.buildings.every(b=>b.o.length>=3&&b.o.every(p=>p.length===2&&p.every(Number.isFinite))));
 const model=makeCampus(src),bounds=new THREE.Box3().setFromObject(model.group);
 assert.equal(model.group.userData.buildingCount,count);
 assert.ok(bounds.max.x-bounds.min.x<=4.48&&bounds.max.z-bounds.min.z<=4.48,'model must fit 4×4');
 assert.ok(bounds.min.y>=-.005,'no raised platform');
 console.log('PASS:',name,count,'real OSM building outlines loaded into own 3D renderer');
}
let s=initialState('standard');
assert.equal(s.version,13);
s.units=[{id:'a1',team:'ally',kind:'infantry',hp:10,x:8,z:5}];
assert.equal(canMove(s,s.units[0],8,6),null);
const after=resolveTurn(s,{...emptyPlan(),orders:{a1:{type:'move',x:8,z:6}}},{}).state;
assert.equal(after.points['8,6'],'ally','point is captured on move without a separate capture command');
assert.equal(after.turn,2);
let ai=initialState('standard');
ai.units=[{id:'e1',team:'enemy',kind:'infantry',hp:10,x:8,z:5}];ai.enemyGold=0;
const aiAfter=resolveTurn(ai,emptyPlan(),{e1:{type:'move',x:8,z:6}}).state;
assert.equal(aiAfter.points['8,6'],'enemy','AI gets the same auto-capture rule');
let r=initialState('standard');
assert.equal(r.research.ally.active,null);
const rs=resolveTurn(r,emptyPlan(),{}).state;
assert.equal(rs.research.ally.progress.development,3,'research progresses automatically');
assert.equal(canResearch(r,'ally','development'),null);
const game=readFileSync('game.js','utf8'),html=readFileSync('index.html','utf8');
assert.ok(game.includes('function simpleRecruit('));
assert.ok(game.includes('function simpleAttack('));
assert.ok(game.includes("$('#quickRecruit').onclick"));
for(const id of ['quickRecruit','quickScout','quickUndo'])assert.ok(html.includes(`id="${id}"`));
assert.ok(html.includes('data-research-path="economy"'));
assert.ok(html.includes('data-research-path="combat"'));
assert.ok(html.includes('data-research-path="defense"'));
assert.ok(html.includes('data-research-path="science"'));
assert.ok(html.includes('id="advancedTech"'));
assert.ok(html.includes('simple-game-v13.css?v=1'));
assert.ok(html.includes('game.js?v=proportions-v15'));
const license=readFileSync('data/THIRD-PARTY-GEO-DATA.md','utf8');
assert.ok(license.includes('Open Database License'));
console.log('PASS: one-tap contextual battles, mobile quick recruit, auto-research and auto-capture');
