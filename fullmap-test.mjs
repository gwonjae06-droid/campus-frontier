import assert from 'node:assert/strict';
import {initialState,emptyPlan,resolveTurn,canBuild,terrain,passable,ownTerritory,enemyOrders,SIZE,TURN_LIMIT,POINT_KEYS,CENTRAL_POINT,ENEMY_BASE,ENEMY_GATES,victoryPoints} from './simulation.js';
import {TECHS,PROJECTS,canProject} from './growth.js';
assert.equal(SIZE,21);assert.equal(TURN_LIMIT,30);
assert.equal(Object.keys(TECHS).length,12);
assert.equal(POINT_KEYS.length,7);assert.equal(CENTRAL_POINT,'10,10');
assert.equal(terrain(17,17),'enemy-base');assert.equal(passable(17,17),false);
assert.equal(ENEMY_GATES.length,4);
const initial=initialState();assert.equal(initial.version,8);
assert.equal(initial.centralPoint,CENTRAL_POINT);
assert.equal(initial.turn,1);
assert.ok(initial.units.every(u=>u.x>=0&&u.x<SIZE&&u.z>=0&&u.z<SIZE&&passable(u.x,u.z)));
assert.ok(TECHS.roads.requires==='defense');
assert.ok(TECHS.wide.requires==='specialization');
assert.ok(TECHS.integrated.requires==='advanced');
let road=initialState();road.research.ally.done=['defense','roads'];road.gold=15;
assert.equal(canBuild(road,emptyPlan(),'road',5,5),null);
road=resolveTurn(road,{...emptyPlan(),builds:[{type:'road',x:5,z:5}]},{}).state;
assert.ok(road.roads.includes('5,5'));assert.equal(road.gold,19);
let wide=initialState();wide.research.ally.done=['development','specialization','wide'];wide.points['8,6']='ally';wide.pointReady['8,6']=1;
assert.equal(canProject(wide,emptyPlan(),{type:'wide',site:'8,6'},0),null);
wide=resolveTurn(wide,{...emptyPlan(),projects:[{type:'wide',site:'8,6'}]},{}).state;
assert.equal(wide.wideSite,'8,6');
assert.equal(ownTerritory(wide,{team:'ally',x:10,z:6}),true);
assert.ok(canProject(wide,emptyPlan(),{type:'wide',site:'6,9'},0));
let grand=initialState();grand.gold=40;grand.research.ally.done=['methodology','advanced','integrated'];
assert.equal(canProject(grand,emptyPlan(),{type:'grand',site:'home'},40),null);
const p={...emptyPlan(),projects:[{type:'grand',site:'home'}]};
grand=resolveTurn(grand,p,{}).state;assert.equal(grand.gold,30);assert.ok(grand.grandConstruction);assert.equal(grand.grandCompleted,false);
const blocked=canBuild(grand,emptyPlan(),'recruit',3,1);assert.ok(blocked);
grand=resolveTurn(grand,emptyPlan(),{}).state;assert.equal(grand.grandCompleted,false);
const scoreBefore=victoryPoints(grand);
grand=resolveTurn(grand,emptyPlan(),{}).state;assert.equal(grand.grandCompleted,true);
assert.equal(victoryPoints(grand),scoreBefore+10);
let tiebreak=initialState();tiebreak.turn=30;tiebreak.homeHP=25;tiebreak.enemyHP=20;
const ended=resolveTurn(tiebreak,emptyPlan(),{}).state;
assert.equal(ended.result,'victory');assert.equal(ended.victoryMode,'score');
console.log('PASS: 21x21 map, 30 turns, 12 technologies, seven objectives, roads, widened territory, three-turn project and tie-break');
