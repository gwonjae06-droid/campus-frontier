import assert from 'node:assert/strict';
import {initialState,emptyPlan,resolveTurn,enemyOrders,targets,terrain,passable,SIZE,TURN_LIMIT,RIVAL_BASE,RIVAL_GATES,victoryPoints} from './simulation.js';
import {canProject} from './growth.js';
const s=initialState('standard');
assert.equal(s.version,12);assert.equal(s.gameMode,'standard');assert.equal(s.rivalHP,30);
assert.equal(s.rivalGold,10);assert.equal(s.research.rival.done.length,0);
assert.equal(s.units.filter(u=>u.team==='rival').length,2);
assert.equal(terrain(RIVAL_BASE.x,RIVAL_BASE.z),'rival-base');
assert.equal(passable(RIVAL_BASE.x,RIVAL_BASE.z),false);
assert.equal(RIVAL_GATES.length,4);assert.equal(SIZE,21);assert.equal(TURN_LIMIT,30);
const ai=enemyOrders(s);assert.ok(ai.e1);assert.ok(ai.r1);
const tick=resolveTurn(s,emptyPlan(),ai).state;
assert.equal(tick.turn,2);assert.ok(tick.rivalGold>=0&&tick.enemyGold>=0);
assert.ok(tick.units.some(u=>u.team==='rival'));assert.ok(tick.units.some(u=>u.team==='enemy'));
assert.equal(s.turn,1);assert.equal(s.rivalGold,10);
let rivalEco=initialState('standard');rivalEco.points['13,14']='rival';rivalEco.pointReady['13,14']=1;
rivalEco.research.rival.done=['development','specialization'];
assert.equal(canProject(rivalEco,emptyPlan(),{site:'13,14',type:'economy'},10,'rival'),null);
rivalEco=resolveTurn(rivalEco,emptyPlan(),{}).state;
assert.equal(rivalEco.specialties['13,14'],'economy');
let siege=initialState('standard');siege.rivalHP=6;siege.units=[{id:'a1',team:'ally',kind:'siege',x:14,z:3,hp:8}];
assert.ok(targets(siege,siege.units[0]).some(t=>t.kind==='base'&&t.team==='rival'));
const battle=resolveTurn(siege,{...emptyPlan(),orders:{a1:{type:'attack',target:{kind:'base',team:'rival'}}}},{}).state;
assert.equal(battle.rivalHP,0);assert.equal(battle.result,null,'other AI still alive');
assert.equal(battle.capturePoints.ally,10);
let final=initialState('standard');final.turn=30;final.units=[];final.research.ally.done=['training'];
final=resolveTurn(final,emptyPlan(),{}).state;
assert.equal(final.result,'victory');assert.equal(final.victoryMode,'score');assert.equal(final.winner,'ally');
const legacy=initialState();assert.equal(legacy.version,8);assert.equal(legacy.rivalHP,undefined);
let campaign=initialState('standard');
for(let i=0;i<TURN_LIMIT&&!campaign.result;i++){
 const prior=campaign;campaign=resolveTurn(campaign,emptyPlan(),enemyOrders(campaign)).state;
 assert.equal(campaign.turn,prior.turn+1);
 assert.ok(campaign.gold>=0&&campaign.enemyGold>=0&&campaign.rivalGold>=0);
 assert.ok([campaign.homeHP,campaign.enemyHP,campaign.rivalHP].every(v=>v>=0&&v<=30));
 assert.ok(campaign.units.every(u=>u.hp>0&&Number.isFinite(u.hp)&&passable(u.x,u.z)));
 assert.ok(campaign.units.every((u,i)=>campaign.units.findIndex(v=>v.x===u.x&&v.z===u.z)===i),'overlapping units');
 for(const team of ['ally','enemy','rival'])assert.ok(campaign.research[team].bank>=0&&campaign.research[team].bank<=10);
}
assert.ok(['victory','defeat','draw'].includes(campaign.result),'campaign must conclude in 30 turns');
console.log('PASS: 30-turn three-way deterministic stress simulation');
console.log('PASS: 3-faction startup, 2 AI turn plans, rival economy, rival campus combat/capture, 30-turn score, practice compatibility');
