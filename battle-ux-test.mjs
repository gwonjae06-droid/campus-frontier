import assert from 'node:assert/strict';
import {createSequentialGame,previewAttack,applySequentialAction,scoreBreakdown,endSequentialRound} from './sequential-mode.js';
import {visibleEvents,describeEvent,publicScore} from './battle-report.js';

const original=createSequentialGame({playerTeam:'ally',seed:42});
assert.equal(scoreBreakdown(original,'ally').total,30);
assert.equal(publicScore(original,'enemy'),null,'unrevealed enemy score is private');
const combat=structuredClone(original);
const attacker=combat.units.find(u=>u.id==='a1');
const victim=combat.units.find(u=>u.id==='e1');
attacker.x=10;attacker.z=10;victim.x=10;victim.z=11;
const target={kind:'unit',id:victim.id};
const snapshot=structuredClone(combat);
const preview=previewAttack(combat,'ally',attacker.id,target);
assert.ok(!preview.error,preview.error);
const applied=applySequentialAction(combat,{type:'attack',id:attacker.id,target});
assert.ok(!applied.error,applied.error);
assert.equal(applied.state.units.find(u=>u.id===victim.id).hp,preview.remainingHp,'preview is exact');
assert.deepEqual(combat,snapshot,'attack and preview do not mutate input');
assert.ok(previewAttack(applied.state,'ally',attacker.id,target).error,'spent action is rejected');
const hidden=visibleEvents([{type:'move',team:'enemy',from:{x:12,z:15},to:{x:12,z:16}}],original,original,'ally');
assert.equal(hidden.length,0,'hidden troop movement stays concealed');
const observed=visibleEvents([{type:'capture',team:'ally',x:6,z:3}],original,original,'ally');
assert.equal(observed.length,1);
assert.match(describeEvent(observed[0]),/거점 점령/);
const round=endSequentialRound(original);
assert.ok(!round.error);
assert.ok(round.phases.every(x=>Array.isArray(x.events)),'each phase returns events');
assert.deepEqual(round.phases.flatMap(x=>x.events),round.events.filter(x=>x.type!=='income'&&x.type!=='score'));
console.log('battle-ux-test: OK');
